/**
 * Единая точка защиты по СОДЕРЖИМОМУ текста, а не по имени поля объекта
 * (риск №5 из плана — "секреты никогда не идут ... в error message").
 * Ни один адаптер сегодня не кладёт секрет в текст исключения (проверено
 * тестами каждого адаптера), но это единственная гарантия, что БУДУЩАЯ
 * ошибка (в этом или любом другом коде) не пробьёт защиту тихо — применяется
 * в `PipelineOrchestrator.fail()` и в error-сериализаторе `technicalLogger`
 * (Milestone 12), то есть в двух местах, через которые проходит вообще
 * любое исключение, а не полагается на дисциплину каждого нового вызывающего
 * кода.
 *
 * Паттерны намеренно консервативны (длинные alnum-последовательности) —
 * чтобы не давать ложных срабатываний на короткие, человекочитаемые тестовые
 * фикстуры вида `sk-test-secret`/`fake-pat-token`, которые реальным секретам
 * по форме не соответствуют.
 */
const SECRET_PATTERNS: RegExp[] = [
  /Bearer\s+[A-Za-z0-9_-]{20,}/gi,
  /sk-[A-Za-z0-9_-]{20,}/g,
  /AKIA[0-9A-Z]{16}/g,
  /-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?-----END [A-Z ]*PRIVATE KEY-----/g,
];

export function redactSecrets(text: string): string {
  let result = text;
  for (const pattern of SECRET_PATTERNS) {
    result = result.replace(pattern, '[REDACTED]');
  }
  return result;
}
